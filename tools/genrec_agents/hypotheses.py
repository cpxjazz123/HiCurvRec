"""The autonomous hypothesis step (issue #105, workstream B).

The research system's next hypotheses are generated by the agent from what the evidence
store actually holds -- not from a paragraph of prior outcomes written into the code. The
store's manifests are rendered into a brief; the agent answers with hypotheses that name
their rival explanations, their falsifiable predictions, and the experiment that would
discriminate between them; and the controller ranks the proposed experiments by expected
information gain per unit of cost, with a deterministic rule.

The ledger this writes is the only thing the next stage reads, so a claim that is not
backed by a run in the store cannot reach the next mechanism.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from .evidence import EvidenceStore, now_utc
from .ledger import Explanation, Experiment, Hypothesis, Ledger, Prediction

REPO_ROOT = Path(__file__).resolve().parents[2]


@dataclass
class Candidate:
    """One hypothesis as the agent proposed it, before it is admitted to the ledger."""

    id: str
    observation: str
    explanations: List[Explanation]
    experiments: List[Experiment]
    evidence_runs: List[str]
    notes: str = ""


def store_brief(store: EvidenceStore) -> str:
    """What the store holds, rendered for the agent. Every number is read from a manifest."""
    manifests = store.runs()
    lines: List[str] = []
    for manifest in manifests:
        metrics = manifest.get("metrics") or {}
        evaluation = metrics.get("frozen_evaluation") or {}
        sensitivity = metrics.get("export_sensitivity") or {}
        stage3 = metrics.get("stage3") or {}
        discrimination = (sensitivity.get("train_side_discrimination") or {})
        arm = discrimination.get("arm") or {}
        control = discrimination.get("control") or {}
        lines.append(
            f"* {manifest['run_id']} [{manifest['kind']}] {manifest['mechanism_id']}: "
            f"status={manifest['status']}, epochs={metrics.get('epochs')}, "
            f"Hard-L1 ER={evaluation.get('hard_l1_er')} "
            f"(gate {evaluation.get('frozen_threshold')}, "
            f"bootstrap {evaluation.get('bootstrap_ci95')}), "
            f"export={sensitivity.get('verdict')} "
            f"(changed L1 {((sensitivity.get('changed_fraction') or {}).get('levels_1'))}), "
            f"level-0 occupancy ratio vs control="
            f"{sensitivity.get('level0_occupancy_ratio_vs_control')}, "
            f"train-side discrimination arm={arm.get('discrimination')} "
            f"control={control.get('discrimination')}, "
            f"Stage-3 recall@10={stage3.get('test_recall@10')} "
            f"ndcg@10={stage3.get('test_ndcg@10')}"
        )
    return "\n".join(lines) if lines else "(the store is empty)"


def _brief(store: EvidenceStore) -> str:
    return f"""# ROLE

You are the research scientist of an autonomous system. You do not write code and you do
not run anything. You are given what the system has MEASURED, and you propose the
hypotheses that should be tested next.

# WHAT THE SYSTEM HAS MEASURED (every number is from a run manifest in the evidence store)

{store_brief(store)}

# THE SITUATION

Two things happened that the system cannot yet explain, and both of them matter more than
any single mechanism's score:

1. Two arms' exported SIDs are **bit-identical** to the matched control's, even though
   their training losses differ. A term that shapes only the encoder's continuous loss
   does not reach the decision that exports the SIDs.
2. Two arms cleared the frozen Hard-L1 ER gate and **neither improved Stage-3
   recommendation quality**; one of them produced the best Hard-L1 ER of the whole
   campaign and still did not improve recall@10. A third arm raised the ER and made
   recall@10 clearly worse.

# WHAT YOU MUST PRODUCE

At least **three materially distinct** hypotheses about these observations -- not three
phrasings of one. "Different" means: they disagree about which mechanism is responsible
and therefore predict different measurements.

Among them, at least one MUST be about the second situation above (why a rising ER does
not buy Stage-3 quality), and it must consider at least these rival explanations, which
you may extend:

* the ER gain is concentrated in a few items rather than spread over the catalogue, so it
  does not change what a recommender can exploit;
* the codes' NEIGHBOURHOOD structure changed (how many distinct codes a transition's
  neighbourhood spans, how the prefixes are distributed), which is what a beam search
  over codes actually consumes, while the pair-level ER improves;
* the codes' stability across training or across the three levels changed in a way the
  pair-level ER cannot see;
* the Stage-3 difference is inside the run-to-run noise of the Stage-3 trainer.

Do not assume that correlation implies causation, and do not assume the ER is the
objective: the project's objective is downstream recommendation quality, and the ER is
only an admission signal.

# THE FORMAT

Reply with ONE fenced ```json block and nothing else:

```json
{{
  "hypotheses": [
    {{
      "id": "H105-01",
      "observation": "what was observed, in one sentence, naming the run ids",
      "evidence_runs": ["run-id-from-the-store"],
      "explanations": [
        {{
          "id": "E1",
          "statement": "one rival account of the observation",
          "predictions": [
            {{
              "id": "P1",
              "statement": "a falsifiable prediction",
              "falsifier": "the measurement that would refute it",
              "measurement": "how it is measured, exactly"
            }}
          ]
        }}
      ],
      "experiments": [
        {{
          "id": "X1",
          "tests": ["E1"],
          "control_run": "the run id of the matched control",
          "treatment_runs": ["run id of the arm"],
          "information_gain": 3,
          "cost": "none",
          "cost_units": 0,
          "decision": "what decision the outcome would drive"
        }}
      ],
      "notes": "anything the controller should know"
    }}
  ]
}}
```

`information_gain` is your estimate, from 1 (barely informative) to 5 (would settle the
question), of how much the experiment reduces the uncertainty about the hypothesis.
`cost_units` is 0 for an analysis over artifacts that already exist, 1 for a probe
(minutes) and 2 for a cold Stage-2 run (hours). The controller ranks experiments by
information gain per cost unit, so an analysis that settles a question is preferred over
a run that might.

Every hypothesis must name the run ids it rests on, and every experiment must name the
matched control it is compared against.
"""


def _parse(text: str) -> List[Candidate]:
    import re

    block = re.search(r"```json\s*(\{.*?\})\s*```", text, re.S)
    raw = block.group(1) if block else None
    if raw is None:
        start = text.find("{")
        end = text.rfind("}")
        raw = text[start : end + 1] if start >= 0 and end > start else ""
    document = json.loads(raw)
    candidates: List[Candidate] = []
    for item in document.get("hypotheses") or ():
        explanations = [
            Explanation(
                id=entry["id"],
                statement=entry["statement"],
                predictions=[
                    Prediction(
                        id=prediction["id"],
                        statement=prediction["statement"],
                        falsifier=prediction["falsifier"],
                        measurement=prediction.get("measurement", ""),
                    )
                    for prediction in entry.get("predictions") or ()
                ],
            )
            for entry in item.get("explanations") or ()
        ]
        experiments = []
        for entry in item.get("experiments") or ():
            experiment = Experiment(
                id=entry["id"],
                tests=list(entry.get("tests") or ()),
                control_run=entry.get("control_run"),
                treatment_runs=list(entry.get("treatment_runs") or ()),
                status="planned",
                result="",
                verdict="",
            )
            experiment.info_gain = int(entry.get("information_gain", 1))  # type: ignore[attr-defined]
            experiment.cost_units = float(entry.get("cost_units", 1))  # type: ignore[attr-defined]
            experiment.decision = entry.get("decision", "")  # type: ignore[attr-defined]
            experiments.append(experiment)
        candidates.append(
            Candidate(
                id=item["id"],
                observation=item["observation"],
                explanations=explanations,
                experiments=experiments,
                evidence_runs=list(item.get("evidence_runs") or ()),
                notes=item.get("notes", ""),
            )
        )
    return candidates


def rank_experiments(candidates: List[Candidate]) -> List[Tuple[Candidate, Experiment, float]]:
    """The ranking rule: expected information gain per unit of cost, best first.

    The rule is deterministic and lives in the controller, not in the agent's prose: the
    agent estimates the gain and the cost, and the controller divides.
    """
    scored: List[Tuple[Candidate, Experiment, float]] = []
    for candidate in candidates:
        for experiment in candidate.experiments:
            gain = float(getattr(experiment, "info_gain", 1.0))
            cost = float(getattr(experiment, "cost_units", 1.0))
            if cost <= 0:
                cost = 0.25  # a free analysis is still cheaper than the cheapest run
            scored.append((candidate, experiment, gain / cost))
    scored.sort(key=lambda row: (-row[2], row[0].id, row[1].id))
    return scored


def generate(
    store: EvidenceStore, out_dir: Path, *, model: str = "", timeout: int = 2400
) -> Dict[str, Any]:
    """The agent proposes; the controller parses, ranks and writes the ledger."""
    from . import opencode

    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    result = opencode.run_agent(
        out_dir,
        _brief(store),
        model=model or opencode.model_name(),
        timeout=timeout,
        title="hypotheses",
    )
    (out_dir / "hypotheses_session.json").write_text(
        json.dumps(result, indent=2, default=str) + "\n", encoding="utf-8"
    )
    text = result.get("text") or ""
    (out_dir / "hypotheses_reply.txt").write_text(text, encoding="utf-8")
    candidates = _parse(text)
    ledger = Ledger(out_dir / "ledger.json", store=store)
    for candidate in candidates:
        ledger.add(
            Hypothesis(
                id=candidate.id,
                observation=candidate.observation,
                evidence_runs=candidate.evidence_runs,
                explanations=candidate.explanations,
                experiments=candidate.experiments,
                status="open",
                notes=candidate.notes,
            )
        )
    problems = ledger.problems()
    digest = ledger.save()
    ranked = rank_experiments(candidates)
    report = {
        "generated_utc": now_utc(),
        "candidates": len(candidates),
        "ledger_path": str(ledger.path),
        "ledger_sha256": digest,
        "problems": problems,
        "ranking": [
            {
                "hypothesis": candidate.id,
                "experiment": experiment.id,
                "tests": experiment.tests,
                "information_gain": getattr(experiment, "info_gain", None),
                "cost_units": getattr(experiment, "cost_units", None),
                "score": round(score, 3),
                "decision": getattr(experiment, "decision", ""),
            }
            for candidate, experiment, score in ranked
        ],
    }
    (out_dir / "hypotheses_report.json").write_text(
        json.dumps(report, indent=2, default=str) + "\n", encoding="utf-8"
    )
    return report


