"""Agent contracts for the Issue #120 round: ideate, score, implement, verify, repair.

The prompts state what each role must return and what it must not do. The
verification role is a correctness reviewer of an implementation, not a scientific
paper referee: the issue is explicit that scientific paperwork completeness is
not a pre-training gate, while actual correctness, numerical stability and a
runnable trainer are.
"""
from __future__ import annotations

IDEA_FIELDS = (
    "idea_id, title, motivation, novelty, key_change, specification, cost_estimate, "
    "falsifiable_hypothesis, risks"
)

IDEA_PROMPT = (
    "Propose {minimum} to {maximum} DISTINCT, implementable ideas for improving the "
    "item semantic IDs that a generative recommender consumes. You are one of three "
    "independent ideation agents: aim for a different part of the design space than the "
    "obvious one, and do not copy an existing mechanism in the repository.\n"
    "Write PLAIN TEXT, one block per idea, in exactly this shape:\n"
    "IDEA: <short safe identifier, unique in your answer>\n"
    "TITLE: <one line>\n"
    "MOTIVATION: <the user-behaviour or recommendation problem it addresses>\n"
    "NOVELTY: <what is different from the mechanisms that already exist here>\n"
    "CHANGE: <the computational change, in one or two sentences>\n"
    "SPECIFICATION: <the minimal mathematics or pseudocode an implementer can write "
    "without guessing>\n"
    "COST: <the compute or wall-clock cost relative to the baseline, and the per-step "
    "cost at the FROZEN scale: 24556 training items, 24 steps per epoch, 3000 epochs>\n"
    "HYPOTHESIS: <what must be true for the idea to be worth keeping, and how it would "
    "be observed>\n"
    "RISKS: <what could make it fail>\n"
    "END IDEA\n"
    "A value may run over several lines; the next line that starts with one of the "
    "labels above starts the next value. Unconventional ideas and unfinished "
    "derivations are welcome: only reject an idea that cannot be made minimally "
    "specified. Do NOT propose a proof, a paper section or a quality floor; the ideas "
    "are selected for innovation and then implemented and measured."
)

SCORE_PROMPT = (
    "You are one of three independent evaluators. Score EVERY idea below on five "
    "dimensions from 0 to 5: novelty, scientific_motivation, feasibility, "
    "downstream_impact, experimental_distinctness. Give the numeric scores, a short "
    "rationale and the known uncertainties for each idea. Judge the idea as written: an "
    "unfinished derivation is not a defect, but an idea that cannot be implemented is.\n"
    "Do not rank the ideas against each other and do not veto: your report is one of "
    "three, and the aggregate decides. Do not score on Stage 2 quality diagnostics such "
    "as prefix counts or collision rates; selection is innovation-first.\n"
    "Write PLAIN TEXT, one line per idea, in exactly this shape:\n"
    "SCORE: <idea_id> | novelty=<0-5> | scientific_motivation=<0-5> | "
    "feasibility=<0-5> | downstream_impact=<0-5> | experimental_distinctness=<0-5>\n"
    "RATIONALE: <idea_id> | <why these numbers, and the uncertainties>\n"
    "One SCORE line and one RATIONALE line for every idea, using the idea_id exactly "
    "as it is given."
)

IMPLEMENT_PROMPT = (
    "Implement ONE idea as a standalone Stage 2 candidate tree.\n"
    "The idea:\n{idea}\n"
    "YOUR TREE IS THIS EXACT DIRECTORY, and every file you create must live inside "
    "it:\n{tree}\n"
    "Do not create a tree anywhere else, and do not write your implementation into "
    "your own workspace. The framework reads the files in that directory and ignores "
    "everything you say about them.\n"
    "Requirements:\n"
    "  1. Copy the frozen baseline tree and change only what the idea needs. Keep the "
    "frozen protocol: latent 32, three levels of 256 codes, 3000 epochs, the existing "
    "optimizer, schedule, batch size, seeds, the data split and the exporter.\n"
    "  2. The training must run: a forward and a backward, finite losses, gradients that "
    "reach the parameters the idea changes, a valid SID export, and a minimal smoke test "
    "that proves it.\n"
    "  3. The trainer must be able to run on ONE GPU: keep the frozen trainer's "
    "single-card branch, which reads the environment variable "
    "SINGLE_GPU_ENV = \"GENREC_SINGLE_GPU\", and do not replace the launcher with an "
    "unconditional four-rank torchrun. The round trains several candidates at the "
    "same time, one card each, so a trainer that only forks four ranks cannot be "
    "admitted.\n"
    "  4. The trainer must keep the frozen baseline's own path scheme, so that it "
    "exports item_sids.json, rqvae_best.pth and sids_for_hgrec.npy into "
    "results/stage2_RQ-VAE/<the name of the directory this trainer file lives in>/"
    "<EXPERIMENT_ARM>/. The admission and the Stage 3 trainer look exactly there, so "
    "an export into the tree directory itself is not found.\n"
    "  5. Record every deviation from the idea and every assumption you had to make, "
    "with the reason.\n"
    "  6. Do not change the shared repository outside your own tree. Do not modify the "
    "baseline trees, the MCP server or the verification code.\n"
    "Write PLAIN TEXT about what you did, in exactly this shape:\n"
    "TREE: <the absolute path of the tree you wrote>\n"
    "CHANGED FILE: <one path relative to the tree, one line per file>\n"
    "DEVIATION: <what you changed from the idea> | <why>\n"
    "ASSUMPTION: <one assumption you had to make>\n"
    "SMOKE COMMAND: <the command you ran>\n"
    "SMOKE RESULT: <what it printed>\n"
    "NOTES: <anything the reviewers should know>"
)

VERIFY_PROMPT = (
    "You are one of three independent verifiers of an implementation. Inspect the "
    "code, do not trust a passing test.\n"
    "The idea it implements:\n{idea}\n"
    "The tree:\n{tree}\n"
    "Check three things and report each with file and line references:\n"
    "  a) mechanism fidelity: does the code implement the idea, and only the idea?\n"
    "  b) trainability: does a real forward and backward produce finite losses and "
    "gradients that reach the intended parameters, with no dead term and no "
    "numerically unstable step?\n"
    "  c) integration: does the real trainer entry point run, is the data path the "
    "frozen one, is the SID export valid and correctly indexed, and does the "
    "distributed launcher still work, including the single-card branch that reads "
    "SINGLE_GPU_ENV = \"GENREC_SINGLE_GPU\"?\n"
    "Report PASS or NEEDS_FIX per check. A NEEDS_FIX must name the defect, give a "
    "concrete reproduction or a minimal counterexample, say how severe it is and what "
    "the correction is. Do not demand a proof, a literature review or a quality floor: "
    "this is a correctness review of code, not a scientific paper review.\n"
    "Write PLAIN TEXT, in exactly this shape:\n"
    "VERDICT: PASS or NEEDS_FIX\n"
    "CHECK: <the check you are reporting>\n"
    "CHECK VERDICT: PASS or NEEDS_FIX\n"
    "FINDING SEVERITY: <blocking, or minor when it does not stop the work>\n"
    "FINDING LOCATION: <file:line>\n"
    "FINDING DETAIL: <what is wrong>\n"
    "FINDING REPRODUCTION: <how to see it>\n"
    "FINDING CORRECTION: <what the correction is>\n"
    "Repeat the CHECK block for every check, and the finding lines for every finding."
)

