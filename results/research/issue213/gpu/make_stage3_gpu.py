def main() -> int:
    body = strip_and_rewrite(stage3_body(SOURCE.read_text()))
    OUT_INC.write_text(TEMPLATE.replace("BODY", body))
    print(f"wrote {OUT_INC.name} ({len(body.splitlines())} body lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
