"""Generate the CUDA port of count5's stage 3 (the per-node orbit arithmetic).

    python3 ../gpu/make_stage3_gpu.py        # run inside results/research/issue213/orca

Reads `orca_omp.cpp` (written by make_variants.py), lifts the body of stage 3 out of count5 and
rewrites it as one thread per node:

  * `orbit[x][k]`        -> a local `loc[k]`, written out at the end
  * `adj[y][i]`          -> `NB(y,i)`   (CSR)
  * `inc[y][i].first`    -> `NB(y,i)`;  `.second` -> `EID(y,i)`  (neighbour and edge id)
  * `deg[y]`             -> `DEG(y)`
  * `adjacent(u,v)`      -> `ADJ(u,v)`  (the same bit matrix the CPU build uses)
  * `common2_get(PAIR)`  -> `C2(u,v)`,  `common3_get(TRIPLE)` -> `C3(u,v,w)`
  * `common_x[b]`        -> `C2(x,b)` and `common_a[b]` -> `C2(a,b)`
  * `C5[x]`              -> `C5X(x)` (stage 2's five-clique count, passed to the kernel)

The last substitution is the one that makes the port possible at all: the per-node scratch arrays
`common_x`/`common_a` are exactly the common-neighbour counts the stage-1 tables already hold --
the loops that incremented them walked all of N(x) and skipped x and the neighbours of x, which is
the same set `common2` counts -- so removing them costs nothing and frees the port from n-sized
per-thread state.  Everything else is mechanical, and the result is validated by comparing the full
orbit output with the stock single-threaded run byte for byte.
"""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ORCA_DIR = HERE.parent / "orca"
SOURCE = ORCA_DIR / "orca_omp.cpp"
OUT_INC = ORCA_DIR / "orca_stage3_gpu.inc"

DROP_LINE_PARTS = (
    "int *common_x", "int *common_a", "unordered_map<", "#pragma omp",
    "for (int i=0;i<ncx;i++) common_x", "for (int i=0;i<nca;i++) common_a",
    "common_x_list[ncx++]=b;", "common_a_list[nca++]=c;",
)


def stage3_body(source: str) -> str:
    count5 = source.index("void count5()")
    end = source.index("void ecount5()", count5)
    body = source[count5:end]
    start = body.index('printf("stage 3 - building systems of equations')
    stop = body.index("endTime = clock();", start)
    return body[start:stop]


def strip_and_rewrite(body: str) -> str:
    kept = []
    for line in body.split("\n"):
        stripped = line.strip()
        if stripped.startswith("printf(") or stripped.startswith("frac_prev="):
            continue
        if any(part in stripped for part in DROP_LINE_PARTS):
            continue
        if stripped in ("ncx=0;", "nca=0;", "common_x[b]++;", "common_a[c]++;", "for (int x=0;x<n;x++) {"):
            continue
        kept.append(line)
    text = "\n".join(kept)

    text = re.sub(r"orbit\[x\]\[(\d+)\]", r"loc[\1]", text)
    text = re.sub(r"\badj\[([abcx])\]\[([a-z0-9]+)\]", r"NB(\1,\2)", text)
    text = re.sub(r"\binc\[([abcx])\]\[([a-z0-9]+)\]\.first", r"NB(\1,\2)", text)
    text = re.sub(r"\binc\[([abcx])\]\[([a-z0-9]+)\]\.second", r"EID(\1,\2)", text)
    text = re.sub(r"\bdeg\[([abcx])\]", r"DEG(\1)", text)
    text = text.replace("adjacent(", "ADJ(")
    text = re.sub(r"common2_get\(PAIR\(([^,]+),([^)]+)\)\)", r"C2(\1,\2)", text)
    text = re.sub(r"common3_get\(TRIPLE\(([^,]+),([^,]+),([^)]+)\)\)", r"C3(\1,\2,\3)", text)
    text = text.replace("C5[x]", "C5X(x)")
    text = (text.replace("common_x[c]", "C2(x,c)").replace("common_a[c]", "C2(a,c)")
                .replace("common_a[b]", "C2(a,b)").replace("common_x[b]", "C2(x,b)"))
    # the `for (int x` wrapper was dropped above, so its closing brace has to go too
    while text.count("{") < text.count("}") and text.rstrip().endswith("}"):
        text = text.rstrip()[:-1]
    leftovers = [l.strip() for l in text.split("\n")
                 if re.search(r"\b(common_x|common_a|orbit\[x\]|adj\[|deg\[|inc\[)", l)]
    if leftovers:
        raise SystemExit("unrewritten lines remain: " + repr(leftovers[:3]))
    return text.rstrip() + "\n"


