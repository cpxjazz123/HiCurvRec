"""Issue #283: package the stats output (gzip + manifest + report tables)."""
from __future__ import annotations

import gzip
import json
import sys
from pathlib import Path

sys.path.insert(0, '.')
from results.research.issue283 import joint283 as J


def sha(p):
    return J.sha256(p)


def main() -> None:
    raw = J.P / 'JOIN_TABLE.json'
    import zlib
    blob = raw.read_bytes()
    # split the compressed stream in two files, each < 2 MiB (commit_guard): independent gzip members
    half = len(blob) // 2
    parts = []
    for idx, (lo, hi) in enumerate(((0, half), (half, len(blob))), 1):
        part = J.P / f'JOIN_TABLE.part{idx}.json.gz'
        part.write_bytes(gzip.compress(blob[lo:hi], compresslevel=9, mtime=0))
        parts.append((part, lo, hi))
    gz = parts[0][0]
    summary = json.load(open(J.P / 'JOIN_SUMMARY.json'))
    table = json.load(open(raw))
    entries = table['entries']
    n_sids = len(entries)
    support = table['support']
    # headline per-class/level table (chain/revchain/merge/fork family + triangle + reciprocal)
    lines = ['| class | level | pooled ALL | pooled AM | pooled MB | pooled AB | pooled NONE | ALL lift(u) | ALL lift(d) |',
             '|---|---|---|---|---|---|---|---|---|']
    for name in ('chain', 'revchain', 'fork', 'merge', 'ff', 'fb', 'recip_both', 'recip_a_in'):
        if name not in summary['levels']['1']:
            continue
        for k in ('1', '2', '3'):
            c = summary['levels'][k][name]
            r = c['pooled_rate']
            lines.append(f"| {name} | k={k} | {r[0]:.5f} | {r[1]:.5f} | {r[2]:.5f} | {r[3]:.5f} | {r[4]:.5f} "
                         f"| {c['lift_u_mean']:+.5f} | {c['lift_d_mean']:+.5f} |")
    (J.P / 'TABLES.md').write_text('\n'.join(lines) + '\n')
    # per-SID range of the key features
    feats = {}
    for sha_, rec in entries.items():
        for name, d in rec['classes'].items():
            for k in ('1', '2', '3'):
                lvl = d[k]
                S = sum(lvl['counts'])
                feats.setdefault(f'all{k}_{name}_lift', []).append(lvl['lift']['all_u'])
                feats.setdefault(f'all{k}_{name}', []).append(lvl['counts'][0] / S)
    ranges = {k: {'n': len(v), 'min': round(min(v), 6), 'median': round(float(sorted(v)[len(v) // 2]), 6),
                  'max': round(max(v), 6)} for k, v in feats.items()}
    (J.P / 'FEATURE_RANGES.json').write_text(json.dumps(ranges, indent=1) + '\n')
    for name in ('VALIDATION_CONTEXT.json', 'VALIDATION_COMPOSITION.json'):
        rawv = J.P / name
        gzv = J.P / (name + '.gz')
        gzv.write_bytes(gzip.compress(rawv.read_bytes(), compresslevel=9, mtime=0))
    manifest = {'schema': 'genrec.issue283.stats_manifest/1',
                'n_sids': n_sids, 'classes': table['classes'], 'support': support,
                'files': {
                    'JOIN_TABLE.json': {'bytes': raw.stat().st_size, 'sha256': sha(raw),
                                        'status': 'derived, regenerated by stats283.py; not committed if >= 2 MiB'},
                    'JOIN_TABLE.part1.json.gz': {'bytes': parts[0][0].stat().st_size,
                                                 'sha256': sha(parts[0][0]), 'raw_range': [parts[0][1], parts[0][2]]},
                    'JOIN_TABLE.part2.json.gz': {'bytes': parts[1][0].stat().st_size,
                                                 'sha256': sha(parts[1][0]), 'raw_range': [parts[1][1], parts[1][2]],
                                                 'note': 'the two parts are independent gzip members of the raw JSON halves'},
                    'JOIN_SUMMARY.json': {'bytes': (J.P / 'JOIN_SUMMARY.json').stat().st_size,
                                          'sha256': sha(J.P / 'JOIN_SUMMARY.json')},
                    'ROWS_MANIFEST.json': {'bytes': (J.P / 'ROWS_MANIFEST.json').stat().st_size,
                                           'sha256': sha(J.P / 'ROWS_MANIFEST.json')},
                    'stats283.py': {'sha256': sha('results/research/issue283/stats283.py')},
                    'joint283.py': {'sha256': sha('results/research/issue283/joint283.py')},
                    'VALIDATION_CONTEXT.json.gz': {'bytes': (J.P / 'VALIDATION_CONTEXT.json.gz').stat().st_size,
                                                   'sha256': sha(J.P / 'VALIDATION_CONTEXT.json.gz')},
                    'VALIDATION_COMPOSITION.json.gz': {'bytes': (J.P / 'VALIDATION_COMPOSITION.json.gz').stat().st_size,
                                                       'sha256': sha(J.P / 'VALIDATION_COMPOSITION.json.gz')}}}
    (J.P / 'STATS_MANIFEST.json').write_text(json.dumps(manifest, indent=1) + '\n')
    print(json.dumps({'entries': n_sids, 'raw_bytes': raw.stat().st_size,
                      'part_bytes': [p.stat().st_size for p, _, _ in parts],
                      'sha256': [manifest['files']['JOIN_TABLE.part1.json.gz']['sha256'],
                                 manifest['files']['JOIN_TABLE.part2.json.gz']['sha256']]},
                     indent=1))


if __name__ == '__main__':
    main()
